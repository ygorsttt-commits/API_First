"""Per-project workspaces on disk.

All file paths coming from the AI are untrusted. They are validated against a strict policy before
anything touches the filesystem, and every write is confined to the project's own directory.
"""

from __future__ import annotations

import difflib
import re
import shutil
import uuid
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from app.domain.hashing import canonical_json, sha256_text

_SEGMENT = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9._\-]*$")
_ALLOWED_DOTFILES = {".github", ".gitignore", ".dockerignore", ".env.example"}
_FORBIDDEN_SEGMENTS = {".git", ".ssh", ".aws", "node_modules", "__pycache__", ".terraform"}
_MAX_DEPTH = 8
_MAX_PATH_LEN = 200


class PathPolicyError(ValueError):
    pass


def validate_relative_path(path: str, allowed_prefixes: tuple[str, ...] | None = None) -> str:
    """Return the normalised path or raise PathPolicyError."""
    if not path or len(path) > _MAX_PATH_LEN:
        raise PathPolicyError("path is empty or too long")
    if "\x00" in path or "\\" in path:
        raise PathPolicyError(f"illegal character in path: {path!r}")
    if path.startswith("/") or re.match(r"^[A-Za-z]:", path):
        raise PathPolicyError(f"absolute paths are not allowed: {path!r}")
    parts = PurePosixPath(path).parts
    if len(parts) > _MAX_DEPTH:
        raise PathPolicyError(f"path too deep: {path!r}")
    for seg in parts:
        if seg in ("..", "."):
            raise PathPolicyError(f"relative traversal is not allowed: {path!r}")
        if seg in _FORBIDDEN_SEGMENTS:
            raise PathPolicyError(f"forbidden path segment '{seg}' in {path!r}")
        if seg.startswith("."):
            if seg not in _ALLOWED_DOTFILES:
                raise PathPolicyError(f"hidden path segment '{seg}' is not allowed")
        elif not _SEGMENT.match(seg):
            raise PathPolicyError(f"invalid path segment '{seg}'")
    norm = "/".join(parts)
    # Prefixes ending in "/" allow a directory tree; anything else must match exactly.
    if allowed_prefixes is not None and not any(
        norm.startswith(p) if p.endswith("/") else norm == p for p in allowed_prefixes
    ):
        raise PathPolicyError(f"path {norm!r} is outside this capability's allowed area {allowed_prefixes}")
    return norm


@dataclass(frozen=True)
class FileChange:
    path: str
    change: str  # added | modified | deleted
    diff: str


class WorkspaceManager:
    def __init__(self, root: Path, max_files: int = 200, max_file_bytes: int = 256_000):
        self.root = root.resolve()
        self.max_files = max_files
        self.max_file_bytes = max_file_bytes

    def path_for(self, project_id: str) -> Path:
        # Project ids are UUIDs generated by the backend; refuse anything else.
        uuid.UUID(project_id)
        p = (self.root / project_id).resolve()
        if p.parent != self.root:
            raise PathPolicyError("workspace escapes root")
        return p

    def validate_files(
        self, files: dict[str, str], allowed_prefixes: tuple[str, ...] | None = None
    ) -> dict[str, str]:
        clean: dict[str, str] = {}
        for path, content in files.items():
            norm = validate_relative_path(path, allowed_prefixes)
            if len(content.encode("utf-8")) > self.max_file_bytes:
                raise PathPolicyError(f"{norm} exceeds {self.max_file_bytes} bytes")
            clean[norm] = content
        return clean

    def replace_contents(self, project_id: str, files: dict[str, str]) -> Path:
        """Atomically replace the workspace with exactly `files` (already validated)."""
        if len(files) > self.max_files:
            raise PathPolicyError(f"too many files ({len(files)} > {self.max_files})")
        files = self.validate_files(files)
        target = self.path_for(project_id)
        self.root.mkdir(parents=True, exist_ok=True)
        staging = self.root / f".staging-{project_id}-{uuid.uuid4().hex[:8]}"
        staging.mkdir()
        try:
            for rel, content in files.items():
                dest = (staging / rel).resolve()
                if staging.resolve() not in dest.parents:
                    raise PathPolicyError(f"{rel} escapes the workspace")
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(content, encoding="utf-8")
                dest.chmod(0o644)
            for d in [staging, *[p for p in staging.rglob("*") if p.is_dir()]]:
                d.chmod(0o755)  # readable by the unprivileged sandbox user
            old = None
            if target.exists():
                old = self.root / f".old-{project_id}-{uuid.uuid4().hex[:8]}"
                target.rename(old)
            staging.rename(target)
            if old is not None:
                shutil.rmtree(old, ignore_errors=True)
        finally:
            if staging.exists():
                shutil.rmtree(staging, ignore_errors=True)
        return target

    def read_all(self, project_id: str) -> dict[str, str]:
        base = self.path_for(project_id)
        out: dict[str, str] = {}
        if not base.exists():
            return out
        for p in sorted(base.rglob("*")):
            if p.is_symlink():
                continue  # never follow links
            if p.is_file():
                out[p.relative_to(base).as_posix()] = p.read_text(encoding="utf-8", errors="replace")
        return out


def snapshot_hash(files: dict[str, str]) -> str:
    return sha256_text(canonical_json({k: sha256_text(v) for k, v in sorted(files.items())}))


def diff_snapshots(old: dict[str, str], new: dict[str, str]) -> list[FileChange]:
    changes: list[FileChange] = []
    for path in sorted(set(old) | set(new)):
        before, after = old.get(path), new.get(path)
        if before == after:
            continue
        kind = "added" if before is None else "deleted" if after is None else "modified"
        diff = "".join(
            difflib.unified_diff(
                (before or "").splitlines(keepends=True),
                (after or "").splitlines(keepends=True),
                fromfile=f"a/{path}" if before is not None else "/dev/null",
                tofile=f"b/{path}" if after is not None else "/dev/null",
            )
        )
        changes.append(FileChange(path=path, change=kind, diff=diff))
    return changes
